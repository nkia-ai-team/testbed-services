package com.corebanking.ledger.service;

import com.corebanking.ledger.event.LedgerEventPublisher;
import com.corebanking.ledger.repository.LedgerEntryRepository;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.data.jpa.repository.Query;

import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.Statement;
import java.util.Arrays;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.times;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

/**
 * 원장 대사는 출금 합과 입금 합을 한 SQL 문장으로 구해야 한다. Oracle 은 문장마다 읽기 시점이
 * 달라서, 두 문장으로 나누면 그 사이에 커밋된 이체가 한쪽 합계에만 잡혀 장부가 맞는데도
 * "Ledger reconciliation MISMATCH" 가 난다. 이 시험은 (1) 서비스가 한 문장짜리 저장소 메서드
 * 하나만 부르는지, (2) 그 문장이 실제 SQL 엔진에서 정상 장부는 0, 한쪽 줄만 남은 장부는
 * 0 이 아닌 값을 내는지를 고정한다.
 */
class LedgerReconciliationTest {

    private Connection db;

    @BeforeEach
    void openDatabase() throws Exception {
        db = DriverManager.getConnection("jdbc:h2:mem:ledger-recon-" + System.nanoTime() + ";MODE=Oracle");
        try (Statement s = db.createStatement()) {
            // core-banking/db/init.sql 의 ledger_entries 정의와 같은 열.
            s.execute("CREATE TABLE ledger_entries (id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                    + " transfer_ref VARCHAR2(64) NOT NULL, account_id VARCHAR2(64) NOT NULL,"
                    + " direction VARCHAR2(8) NOT NULL, amount NUMBER(18,2) NOT NULL,"
                    + " created_at TIMESTAMP DEFAULT SYSTIMESTAMP)");
        }
    }

    @AfterEach
    void closeDatabase() throws Exception {
        db.close();
    }

    private void entry(String ref, String account, String direction, String amount) throws Exception {
        try (PreparedStatement ps = db.prepareStatement(
                "INSERT INTO ledger_entries (transfer_ref, account_id, direction, amount) VALUES (?, ?, ?, ?)")) {
            ps.setString(1, ref);
            ps.setString(2, account);
            ps.setString(3, direction);
            ps.setBigDecimal(4, new BigDecimal(amount));
            ps.executeUpdate();
        }
    }

    private void transfer(String ref, String from, String to, String amount) throws Exception {
        entry(ref, from, "DEBIT", amount);
        entry(ref, to, "CREDIT", amount);
    }

    private BigDecimal imbalance() throws Exception {
        try (Statement s = db.createStatement(); ResultSet rs = s.executeQuery(LedgerEntryRepository.IMBALANCE_SQL)) {
            assertTrue(rs.next());
            BigDecimal value = rs.getBigDecimal(1);
            assertFalse(rs.next(), "대사 문장은 한 줄만 돌려줘야 한다");
            return value;
        }
    }

    @Test
    void balanced_ledger_reconciles_to_zero() throws Exception {
        transfer("t-1", "ACC-1", "ACC-2", "100.00");
        transfer("t-2", "ACC-2", "ACC-3", "2500.50");
        transfer("t-3", "ACC-3", "ACC-1", "0.01");

        assertEquals(0, imbalance().compareTo(BigDecimal.ZERO));
    }

    @Test
    void empty_ledger_reconciles_to_zero_not_null() throws Exception {
        BigDecimal value = imbalance();

        assertEquals(0, value.compareTo(BigDecimal.ZERO));
    }

    @Test
    void ledger_with_only_the_debit_line_of_a_transfer_is_caught() throws Exception {
        transfer("t-1", "ACC-1", "ACC-2", "100.00");
        entry("t-2", "ACC-2", "DEBIT", "30.00");

        assertEquals(0, imbalance().compareTo(new BigDecimal("30.00")));
    }

    @Test
    void ledger_with_only_the_credit_line_of_a_transfer_is_caught() throws Exception {
        transfer("t-1", "ACC-1", "ACC-2", "100.00");
        entry("t-2", "ACC-3", "CREDIT", "7.50");

        assertEquals(0, imbalance().compareTo(new BigDecimal("-7.50")));
    }

    @Test
    void imbalance_query_is_one_native_statement_over_both_directions() throws Exception {
        Query query = LedgerEntryRepository.class.getMethod("sumImbalance").getAnnotation(Query.class);

        assertTrue(query.nativeQuery());
        assertEquals(LedgerEntryRepository.IMBALANCE_SQL, query.value());
        String sql = query.value().toUpperCase();
        assertFalse(sql.contains(";"), "한 문장이어야 한다");
        assertEquals(1, sql.split("\\bSELECT\\b", -1).length - 1, "SELECT 가 하나뿐이어야 한다(부질의로 나누지 않는다)");
        assertTrue(sql.contains("'DEBIT'") && sql.contains("'CREDIT'"));
    }

    @Test
    void repository_has_no_per_direction_sum_left_to_split_the_statement_again() {
        assertFalse(Arrays.stream(LedgerEntryRepository.class.getDeclaredMethods())
                        .anyMatch(m -> m.getName().equals("sumAmountByDirection")),
                "방향별 합계 메서드가 다시 생기면 대사가 두 문장으로 돌아갈 수 있다");
    }

    @Test
    void service_returns_the_single_statement_result_and_maps_null_to_zero() {
        LedgerEntryRepository entries = mock(LedgerEntryRepository.class);
        LedgerService service = new LedgerService(entries, mock(LedgerEventPublisher.class));

        when(entries.sumImbalance()).thenReturn(new BigDecimal("-12.00"));
        assertEquals(new BigDecimal("-12.00"), service.sumImbalance());

        when(entries.sumImbalance()).thenReturn(null);
        assertEquals(BigDecimal.ZERO, service.sumImbalance());

        verify(entries, times(2)).sumImbalance();
    }
}
