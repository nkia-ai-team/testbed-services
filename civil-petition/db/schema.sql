-- 민원 접수, 처리 포털 스키마(설계 docs/spec-testbed-vm-3tier.md §2-3). T 와 S 가 같은 파일을 쓴다.
-- psql -v app_user=<앱 계정> 으로 돌린다. 다시 돌려도 같은 상태가 된다.
-- 표의 주인은 앱 계정이다.
\set ON_ERROR_STOP 1
SET ROLE :"app_user";

CREATE TABLE IF NOT EXISTS department (
    dept_id     integer PRIMARY KEY,
    name        varchar(80) NOT NULL,
    parent_id   integer
);

CREATE TABLE IF NOT EXISTS app_user (
    user_id       bigint PRIMARY KEY,
    login_id      varchar(40) NOT NULL UNIQUE,
    password_hash char(64) NOT NULL,
    name          varchar(60) NOT NULL,
    role          varchar(10) NOT NULL CHECK (role IN ('CITIZEN', 'STAFF')),
    dept_id       integer REFERENCES department,
    created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE SEQUENCE IF NOT EXISTS petition_receipt_seq START 2000001;

CREATE TABLE IF NOT EXISTS petition (
    petition_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_no  varchar(20) NOT NULL UNIQUE,
    user_id     bigint NOT NULL REFERENCES app_user,
    dept_id     integer NOT NULL REFERENCES department,
    category    varchar(20) NOT NULL,
    title       varchar(200) NOT NULL,
    body        text NOT NULL,
    status      varchar(12) NOT NULL CHECK (status IN ('RECEIVED', 'IN_PROGRESS', 'COMPLETED')),
    is_public   boolean NOT NULL,
    created_at  timestamptz NOT NULL,
    updated_at  timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS petition_user_created_idx ON petition (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS petition_dept_status_created_idx ON petition (dept_id, status, created_at);
CREATE INDEX IF NOT EXISTS petition_public_created_idx ON petition (created_at) WHERE is_public;
CREATE INDEX IF NOT EXISTS petition_created_idx ON petition (created_at);

CREATE TABLE IF NOT EXISTS petition_attachment (
    attachment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    petition_id   bigint NOT NULL REFERENCES petition ON DELETE CASCADE,
    file_name     varchar(200) NOT NULL,
    size_bytes    integer NOT NULL,
    created_at    timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS petition_attachment_petition_idx ON petition_attachment (petition_id);

CREATE TABLE IF NOT EXISTS petition_history (
    history_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    petition_id bigint NOT NULL REFERENCES petition ON DELETE CASCADE,
    from_status varchar(12),
    to_status   varchar(12) NOT NULL,
    actor_id    bigint NOT NULL,
    note        varchar(400),
    created_at  timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS petition_history_petition_idx ON petition_history (petition_id);

CREATE TABLE IF NOT EXISTS petition_answer (
    petition_id bigint PRIMARY KEY REFERENCES petition ON DELETE CASCADE,
    staff_id    bigint NOT NULL,
    body        text NOT NULL,
    answered_at timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS stats_dept_monthly (
    dept_id      integer NOT NULL REFERENCES department,
    month        date NOT NULL,
    received     integer NOT NULL,
    completed    integer NOT NULL,
    avg_days     numeric(8, 2),
    refreshed_at timestamptz NOT NULL,
    PRIMARY KEY (dept_id, month)
);

-- 보존 기간(2년)이 지난 민원을 옮겨 두는 표(야간 보관 배치).
CREATE TABLE IF NOT EXISTS petition_archive (
    LIKE petition,
    archived_at timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS petition_archive_receipt_idx ON petition_archive (receipt_no);
CREATE TABLE IF NOT EXISTS petition_history_archive (LIKE petition_history);

CREATE TABLE IF NOT EXISTS batch_run (
    run_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job           varchar(20) NOT NULL,
    started_at    timestamptz NOT NULL,
    finished_at   timestamptz NOT NULL,
    rows_affected bigint NOT NULL,
    result        varchar(10) NOT NULL
);

RESET ROLE;
